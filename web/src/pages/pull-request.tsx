function safeNodeId(index: number) {
  return `node_${index}`
}

function buildPrBody(run: RepairRun) {
  if (!run.drift || !run.impact) return ''
  const refs = referenceCounts(run)
  const nodeIndex = new Map(run.impact.graph.nodes.map((node, index) => [node.urn, index]))
  const mermaidLines = run.impact.graph.edges.map((edge) => {
    const source = run.impact!.graph.nodes.find((node) => node.urn === edge.source_urn)
    const target = run.impact!.graph.nodes.find((node) => node.urn === edge.target_urn)
    const sourceColumn = edge.source_columns[0] ?? ''
    const targetColumn = edge.target_columns[0] ?? ''
    return `    ${safeNodeId(nodeIndex.get(edge.source_urn) ?? 0)}["${source?.name ?? 'source'}.${sourceColumn}"] -->|"${edge.transform_operation ?? 'LINEAGE'}"| ${safeNodeId(nodeIndex.get(edge.target_urn) ?? 0)}["${target?.name ?? 'target'}.${targetColumn}"]`
  })
  const fileRows = run.patches.map((patch) => `| \`${patch.file_path}\` | ${patch.kind} | ${patch.valid ? 'Validated' : 'Blocked'} | ${patch.strategy} |`).join('\n')
  const referenceRows = run.patches.flatMap((patch) => patch.references.map((reference) => `| \`${reference.table}\` | \`${reference.column}\` | ${reference.line ?? '—'} | **${reference.status}** | ${reference.detail} |`)).join('\n')
  const unaffected = run.impact.assets.filter((asset) => asset.bucket === 'DOWNSTREAM_UNAFFECTED').map((asset) => `- **${asset.name}** — ${asset.reason}`).join('\n')
  const skipped = run.impact.assets.filter((asset) => asset.bucket === 'SKIPPED').map((asset) => `- **${asset.name}** — ${asset.reason}`).join('\n')

  return `## Summary

Repair ${run.drift.dataset_name}: \`${run.drift.old_column}\` → \`${run.drift.new_column}\` (${run.drift.kind}, ${run.drift.confidence.toFixed(2)} confidence).

${run.drift.rationale}

## Lineage evidence

\`\`\`mermaid
graph LR
${mermaidLines.join('\n')}
\`\`\`

## Files changed

| File | Kind | Gate | Deterministic strategy |
|---|---|---|---|
${fileRows}

## Validation — 0 hallucinated columns · ${refs.resolved}/${refs.total} references resolved

Every generated column reference was resolved before this pull request was allowed to open. A single unresolvable reference blocks its patch from the review set.

| Table | Column | Line | Status | Evidence |
|---|---|---:|---|---|
${referenceRows}

## Downstream but unaffected

${unaffected || 'No downstream assets were insulated from this change.'}

## Correctly skipped

${skipped || 'No catalog assets were explicitly skipped.'}

---

Generated by **Schema-Drift Auto-Repair Agent** · run \`${run.id}\` · evidence read from DataHub.`
}

function MermaidDiagram({ chart }: { chart: string }) {
  const reactId = useId().replaceAll(':', '')
  const [svg, setSvg] = useState('')
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    let active = true
    mermaid.render(`mermaid_${reactId}`, chart)
      .then((result) => {
        if (active) setSvg(result.svg)
      })
      .catch((caught) => {
        if (active) setError(caught instanceof Error ? caught.message : 'Lineage diagram could not be rendered.')
      })
    return () => { active = false }
  }, [chart, reactId])

  if (error) return <div className="rounded-[8px] border border-danger/30 bg-danger/[0.07] p-3 text-[10px] text-[#fda4af]">{error}</div>
  if (!svg) return <div className="h-52 animate-pulse rounded-[8px] border border-border bg-surface-2" />
  return <div className="mermaid-output my-4 overflow-x-auto rounded-[8px] border border-border bg-[#0a0c0f] p-4 text-center" dangerouslySetInnerHTML={{ __html: svg }} />
}

function MarkdownBody({ body }: { body: string }) {
  return (
    <div className="pr-markdown text-[11px] leading-5 text-text-dim">
      <ReactMarkdown
        remarkPlugins={[remarkGfm]}
        components={{
          pre: ({ children }) => <>{children}</>,
          h2: ({ children }) => <h2 className="mb-2 mt-7 border-b border-border pb-2 text-[15px] font-semibold text-text first:mt-0">{children}</h2>,
          p: ({ children }) => <p className="my-2 text-[11px] leading-5 text-text-dim">{children}</p>,
          strong: ({ children }) => <strong className="font-semibold text-text">{children}</strong>,
          ul: ({ children }) => <ul className="my-2 space-y-1.5 pl-5">{children}</ul>,
          li: ({ children }) => <li className="pl-1 text-text-dim marker:text-text-faint">{children}</li>,
          table: ({ children }) => <div className="my-3 overflow-x-auto rounded-[8px] border border-border"><table className="w-full min-w-[680px] border-collapse text-left">{children}</table></div>,
          thead: ({ children }) => <thead className="bg-surface-2 text-[8px] uppercase tracking-[0.1em] text-text-faint">{children}</thead>,
          th: ({ children }) => <th className="border-b border-border px-3 py-2 font-semibold">{children}</th>,
          td: ({ children }) => <td className="border-b border-border/60 px-3 py-2 align-top text-[9px] leading-4 text-text-dim">{children}</td>,
          code: ({ className, children }) => {
            const language = /language-(\w+)/.exec(className ?? '')?.[1]
            if (language === 'mermaid') return <MermaidDiagram chart={String(children).trim()} />
            return <code className={cn('rounded-[4px] border border-border bg-bg px-1 py-0.5 font-mono text-[9px] text-[#c7d2fe]', className)}>{children}</code>
          },
          hr: () => <hr className="my-6 border-0 border-t border-border" />,
        }}
      >
        {body}
      </ReactMarkdown>
    </div>
  )
}

export function PullRequestPage() {
  const { currentRun, currentRunLoading } = useApp()
  const [copied, setCopied] = useState(false)
  const [payloadOpen, setPayloadOpen] = useState(false)
  const body = useMemo(() => currentRun ? buildPrBody(currentRun) : '', [currentRun])
  const stats = useMemo(() => {
    const lines = currentRun?.patches.flatMap((patch) => patch.unified_diff.split('\n')) ?? []
    return {
      additions: lines.filter((line) => line.startsWith('+') && !line.startsWith('+++')).length,
      deletions: lines.filter((line) => line.startsWith('-') && !line.startsWith('---')).length,
    }
  }, [currentRun])

  const copyBody = async () => {
    await navigator.clipboard.writeText(body)
    setCopied(true)
    window.setTimeout(() => setCopied(false), 1600)
  }

  if (currentRunLoading) return <><PageHeader eyebrow="Review package" title="Pull Request" detail="Loading the latest review artifact." /><LoadingPanel rows={8} className="min-h-[540px]" /></>

  if (!currentRun?.pr || !currentRun.impact) {
    return (
      <div>
        <PageHeader eyebrow="Review package" title="Pull Request" detail="Lineage evidence, patch strategy, and validation in one review surface." />
        <EmptyState icon={currentRun?.status === 'running' ? GitBranch : GitPullRequest} title={currentRun?.status === 'running' ? 'Preparing the review package' : 'No pull request package yet'} detail={currentRun?.status === 'running' ? 'Validated patches will appear here after the hard reference gate passes.' : 'Complete a repair run to render its full review-ready pull request body.'} />
      </div>
    )
  }

  const pr = currentRun.pr
  return (
    <div>
      <PageHeader
        eyebrow="Review package"
        title="Pull Request"
        detail="The exact artifact a reviewer receives, including lineage and negative impact evidence."
        actions={<Badge variant={pr.ok ? 'ok' : 'danger'}><ShieldCheck className="size-3" />{pr.ok ? 'Ready for review' : 'Provider error'}</Badge>}
      />

      <Card className="overflow-hidden border-[#30363d] bg-[#0d1117]">
        <div className="border-b border-[#30363d] px-5 py-4">
          <div className="flex items-start justify-between gap-5">
            <div className="min-w-0">
              <div className="flex items-center gap-2"><GitPullRequest className="size-5 text-[#a371f7]" /><h1 className="m-0 truncate text-[18px] font-semibold text-[#f0f6fc]">{pr.title ?? `Repair ${currentRun.drift?.dataset_name} schema drift`}</h1></div>
              <div className="mt-2 flex flex-wrap items-center gap-2 text-[10px] text-[#8b949e]">
                <Badge variant="ok" className="border-[#238636] bg-[#238636] text-white">Open</Badge>
                <span>schema-drift-repair wants to merge</span>
                <span className="rounded-[5px] border border-[#388bfd66] bg-[#388bfd26] px-2 py-0.5 font-mono text-[9px] text-[#58a6ff]">{pr.branch}</span>
                <span>into</span>
                <span className="rounded-[5px] border border-[#30363d] bg-[#161b22] px-2 py-0.5 font-mono text-[9px] text-[#c9d1d9]">main</span>
              </div>
            </div>
            <div className="flex shrink-0 items-center gap-2">
              <Button variant="outline" size="sm" onClick={() => void copyBody()}>{copied ? <Check className="size-3.5 text-ok" /> : <Clipboard className="size-3.5" />}{copied ? 'Copied' : 'Copy body'}</Button>
              {pr.mode === 'live' ? (
                <a href={pr.url} target="_blank" rel="noreferrer" className="flex h-8 items-center gap-1.5 rounded-[8px] border border-[#238636] bg-[#238636] px-3 text-[11px] font-semibold text-white no-underline hover:bg-[#2ea043]">Open on GitHub <ExternalLink className="size-3" /></a>
              ) : <Button variant="secondary" size="sm" onClick={() => setPayloadOpen(true)}>Dry-run · view payload</Button>}
            </div>
          </div>
          <div className="mt-4 flex items-center gap-4 border-t border-[#21262d] pt-3 text-[10px] text-[#8b949e]">
            <span className="flex items-center gap-1.5"><FileCode2 className="size-3" />{pr.files.length} files changed</span>
            <span className="flex items-center gap-1 font-mono text-[#3fb950]"><Plus className="size-3" />{stats.additions}</span>
            <span className="flex items-center gap-1 font-mono text-[#f85149]"><Minus className="size-3" />{stats.deletions}</span>
            <span className="h-2 w-20 overflow-hidden rounded-sm bg-[#f85149]"><span className="block h-full bg-[#3fb950]" style={{ width: `${(stats.additions / Math.max(1, stats.additions + stats.deletions)) * 100}%` }} /></span>
          </div>
        </div>

        <div className="mx-auto max-w-[940px] px-6 py-6">
          <MarkdownBody body={body} />
        </div>
      </Card>

      <Dialog open={payloadOpen} onOpenChange={setPayloadOpen} title="Dry-run pull request payload" description="The provider wrote this review body locally; no remote branch or PR was created.">
        <div className="mb-3 grid grid-cols-[100px_1fr] gap-y-2 rounded-[8px] border border-border bg-bg p-3 text-[10px]">
          <span className="text-text-faint">Branch</span><span className="font-mono text-text-dim">{pr.branch}</span>
          <span className="text-text-faint">Base</span><span className="font-mono text-text-dim">main</span>
          <span className="text-text-faint">Files</span><span className="font-mono text-text-dim">{pr.files.length}</span>
          <span className="text-text-faint">Provider URL</span><span className="truncate font-mono text-text-dim">{pr.url}</span>
        </div>
        <pre className="m-0 max-h-[52vh] overflow-auto whitespace-pre-wrap rounded-[8px] border border-border bg-[#090b0e] p-4 font-mono text-[9px] leading-5 text-text-dim">{body}</pre>
      </Dialog>
    </div>
  )
}
